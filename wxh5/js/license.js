const PRO_APP_ID = 'meetlog.pro';

let requestPrivateKey = null;
let licensePrivateKey = null;

function pemToArrayBuffer(pem) {
    const lines = pem.split('\n');
    let base64 = '';
    for (const line of lines) {
        if (line.indexOf('-----') === -1) {
            base64 += line.trim();
        }
    }
    const binary = atob(base64);
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) {
        bytes[i] = binary.charCodeAt(i);
    }
    return bytes.buffer;
}

async function importKeys() {
    if (requestPrivateKey && licensePrivateKey) {
        return;
    }

    requestPrivateKey = await crypto.subtle.importKey(
        'pkcs8',
        pemToArrayBuffer(REQUEST_PRIVATE_KEY_PEM),
        {
            name: 'RSA-OAEP',
            hash: 'SHA-256',
        },
        false,
        ['decrypt']
    );

    licensePrivateKey = await crypto.subtle.importKey(
        'pkcs8',
        pemToArrayBuffer(LICENSE_PRIVATE_KEY_PEM),
        {
            name: 'RSASSA-PKCS1-v1_5',
            hash: 'SHA-256',
        },
        false,
        ['sign']
    );
}

function base64UrlDecode(str) {
    let base64 = str.replace(/-/g, '+').replace(/_/g, '/');
    const pad = base64.length % 4;
    if (pad) {
        base64 += '='.repeat(4 - pad);
    }
    const binary = atob(base64);
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) {
        bytes[i] = binary.charCodeAt(i);
    }
    return bytes.buffer;
}

function base64UrlEncode(buffer) {
    const bytes = new Uint8Array(buffer);
    let binary = '';
    for (let i = 0; i < bytes.length; i++) {
        binary += String.fromCharCode(bytes[i]);
    }
    const base64 = btoa(binary);
    return base64.replace(/\+/g, '-').replace(/\//g, '_').replace(/=/g, '');
}

async function sha256(text) {
    const encoder = new TextEncoder();
    const data = encoder.encode(text);
    const hash = await crypto.subtle.digest('SHA-256', data);
    const hashArray = Array.from(new Uint8Array(hash));
    return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
}

function maskDeviceId(deviceId) {
    if (deviceId.length <= 8) {
        return deviceId;
    }
    return deviceId.substring(0, 4) + '****' + deviceId.substring(deviceId.length - 4);
}

async function decryptRequest(ciphertext) {
    const decrypted = await crypto.subtle.decrypt(
        {
            name: 'RSA-OAEP',
        },
        requestPrivateKey,
        base64UrlDecode(ciphertext)
    );
    const decoder = new TextDecoder();
    return JSON.parse(decoder.decode(decrypted));
}

async function signLicense(payload) {
    const encoder = new TextEncoder();
    const payloadJson = buildPayloadJson(payload);
    const payloadBytes = encoder.encode(payloadJson);
    
    const signature = await crypto.subtle.sign(
        {
            name: 'RSASSA-PKCS1-v1_5',
        },
        licensePrivateKey,
        payloadBytes
    );
    
    return {
        payload: base64UrlEncode(payloadBytes),
        signature: base64UrlEncode(signature),
    };
}

function buildPayloadJson(payload) {
    const ordered = {
        a: payload.a,
        f: payload.f,
        l: payload.l,
        n: payload.n,
        i: payload.i,
    };

    if (payload.e !== undefined) {
        ordered.e = payload.e;
    }

    return JSON.stringify(ordered);
}

async function generateLicense() {
    const requestInput = document.getElementById('request').value.trim();
    const orderNo = document.getElementById('orderNo').value.trim();
    const expiresAtInput = document.getElementById('expiresAt').value;
    
    if (!requestInput) {
        showError('请输入设备激活请求');
        return;
    }
    
    if (!orderNo) {
        showError('请输入订单号');
        return;
    }
    
    showLoading(true);
    hideResult();
    
    try {
        await importKeys();
        
        const request = await decryptRequest(requestInput);
        
        if (request.a !== PRO_APP_ID) {
            throw new Error('无效的 App ID');
        }
        
        const fingerprint = await sha256(`${PRO_APP_ID}|${request.t}|${request.d}`);
        
        const payload = {
            a: PRO_APP_ID,
            f: fingerprint,
            l: 'pro',
            n: orderNo,
            i: Date.now(),
        };
        
        if (expiresAtInput) {
            payload.e = new Date(expiresAtInput).getTime();
        }
        
        const { payload: payloadB64, signature } = await signLicense(payload);
        const licenseCode = `${payloadB64}.${signature}`;
        
        showDeviceinfo({
            appId: request.a,
            deviceIdType: request.t,
            maskedDeviceId: maskDeviceId(request.d),
            fingerprint: fingerprint,
            issuedAt: new Date(payload.i).toLocaleString('zh-CN'),
            expiresAt: payload.e ? new Date(payload.e).toLocaleString('zh-CN') : '永久有效',
        });
        
        showSuccess(licenseCode);
    } catch (error) {
        console.error(error);
        showError('生成失败: ' + error.message);
    } finally {
        showLoading(false);
    }
}

function showLoading(show) {
    document.getElementById('loading').classList.toggle('show', show);
    document.getElementById('generateBtn').disabled = show;
}

function hideResult() {
    const result = document.getElementById('result');
    result.classList.remove('show', 'success', 'error');
}

function showSuccess(licenseCode) {
    const result = document.getElementById('result');
    result.classList.add('show', 'success');
    document.getElementById('resultTitle').textContent = '激活码生成成功';
    document.getElementById('licenseCode').textContent = licenseCode;
}

function showError(message) {
    const result = document.getElementById('result');
    result.classList.add('show', 'error');
    document.getElementById('resultTitle').textContent = '错误';
    document.getElementById('deviceInfo').innerHTML = '';
    document.getElementById('licenseCode').textContent = message;
}

function showDeviceinfo(info) {
    const deviceInfo = document.getElementById('deviceInfo');
    deviceInfo.innerHTML = `
        <div><strong>App ID:</strong> ${info.appId}</div>
        <div><strong>设备标识类型:</strong> ${info.deviceIdType}</div>
        <div><strong>设备标识:</strong> ${info.maskedDeviceId}</div>
        <div><strong>设备指纹:</strong> ${info.fingerprint.substring(0, 16)}...</div>
        <div><strong>签发时间:</strong> ${info.issuedAt}</div>
        <div><strong>有效期:</strong> ${info.expiresAt}</div>
    `;
}

function copyLicense() {
    const licenseCode = document.getElementById('licenseCode').textContent;
    navigator.clipboard.writeText(licenseCode).then(() => {
        const btn = document.querySelector('.copy-btn');
        const originalText = btn.textContent;
        btn.textContent = '已复制!';
        setTimeout(() => {
            btn.textContent = originalText;
        }, 2000);
    });
}

